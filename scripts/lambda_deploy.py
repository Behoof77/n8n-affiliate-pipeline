REGION = "ap-south-1"
SITE_NAME = "om-explainer"
ROLE_NAME = "om-lambda-exec"
LAYER_NAME = "om-ffmpeg-layer"
PREP_FN = "om-prep"
DISPATCH_FN = "om-dispatch"
API_NAME = "om-render-api"
PUBLIC_ORIGIN = "https://agenticflow1.duckdns.org"
COMPOSITION = "Explainer"
ENTRY = "src/index.tsx"
FFMPEG_URL = "https://johnvansickle.com/ffmpeg/releases/ffmpeg-release-amd64-static.tar.xz"

ROOT = Path(__file__).resolve().parents[1]
PREP_DIR = ROOT / "lambda" / "prep"
DISPATCH_DIR = ROOT / "lambda" / "dispatch"
SITE_DIR = ROOT / "remotion-site"
LAMBDA_ENV = ROOT / "lambda.env"


def step(msg: str) -> None:
    print(f"==> {msg}", flush=True)


def die(msg: str) -> "None":
    print(f"ERROR: {msg}", file=sys.stderr, flush=True)
    sys.exit(1)


def ensure_creds() -> None:
    for src, dst in (
        ("REMOTION_AWS_ACCESS_KEY_ID", "AWS_ACCESS_KEY_ID"),
        ("REMOTION_AWS_SECRET_ACCESS_KEY", "AWS_SECRET_ACCESS_KEY"),
    ):
        if not os.environ.get(dst) and os.environ.get(src):
            os.environ[dst] = os.environ[src]
    if not os.environ.get("AWS_ACCESS_KEY_ID") or not os.environ.get("AWS_SECRET_ACCESS_KEY"):
        die("set AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY (or REMOTION_AWS_*) first")
    os.environ["AWS_REGION"] = os.environ["AWS_DEFAULT_REGION"] = REGION
    os.environ["REMOTION_AWS_REGION"] = REGION


def read_env_file() -> dict[str, str]:
    out: dict[str, str] = {}
    if LAMBDA_ENV.exists():
        for line in LAMBDA_ENV.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                out[k.strip()] = v.strip()
    return out


def write_env_file(values: dict[str, str]) -> None:
    header = "# generated by scripts/lambda_deploy.py - gitignored via *.env, never commit\n"
    body = "".join(f"{k}={v}\n" for k, v in values.items())
    LAMBDA_ENV.write_text(header + body, encoding="utf-8")
    step(f"wrote {LAMBDA_ENV.name} (gitignored)")


# ---------------------------------------------------------------- IAM / S3 / layer
def ensure_role(sts) -> str:
    import boto3

    iam = boto3.client("iam", region_name=REGION)
    arn = f"arn:aws:iam::{sts.get_caller_identity()['Account']}:role/{ROLE_NAME}"
    trust = {
        "Version": "2012-10-17",
        "Statement": [{"Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"}],
    }
    try:
        iam.get_role(RoleName=ROLE_NAME)
        step(f"IAM role {ROLE_NAME} exists")
    except iam.exceptions.NoSuchEntityException:
        step(f"creating IAM role {ROLE_NAME}")
        iam.create_role(RoleName=ROLE_NAME, AssumeRolePolicyDocument=json.dumps(trust),
                        Description="Remotion pipeline exec role (prep/dispatch)")
        time.sleep(10)
    iam.attach_role_policy(RoleName=ROLE_NAME,
                           PolicyArn="arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole")
    acct = sts.get_caller_identity()["Account"]
    iam.put_role_policy(
        RoleName=ROLE_NAME,
        PolicyName="om-render-inline",
        PolicyDocument=json.dumps({
            "Version": "2012-10-17",
            "Statement": [
                {"Effect": "Allow", "Action": ["s3:GetObject", "s3:PutObject"],
                 "Resource": [f"arn:aws:s3:::om-prep-assets-*", "arn:aws:s3:::*"]},
                {"Effect": "Allow", "Action": ["lambda:InvokeFunction"],
                 "Resource": f"arn:aws:lambda:{REGION}:{acct}:function:*"},
            ],
        }),
    )
    return arn


def ensure_bucket(sts) -> str:
    import boto3
    from botocore.exceptions import ClientError

    acct = sts.get_caller_identity()["Account"]
    name = f"om-prep-assets-{acct}-aps1"
    s3 = boto3.client("s3", region_name=REGION)
    try:
        s3.head_bucket(Bucket=name)
        step(f"bucket {name} exists")
    except ClientError:
        step(f"creating bucket {name}")
        s3.create_bucket(Bucket=name, CreateBucketConfiguration={"LocationConstraint": REGION})
    return name


def _zip_bytes(entries: list[tuple[str, bytes, int]]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for arc, data, mode in entries:
            zi = zipfile.ZipInfo(arc)
            zi.external_attr = (mode & 0xFFFF) << 16
            zf.writestr(zi, data)
    return buf.getvalue()


def ensure_layer(s3, bucket: str) -> str:
    import boto3
    import tarfile as tf

    lam = boto3.client("lambda", region_name=REGION)
    existing = lam.list_layer_versions(LayerName=LAYER_NAME).get("Versions")
    if existing:
        arn = existing[0]["LayerVersionArn"]
        step(f"layer {LAYER_NAME} v{existing[0]['Version']} exists")
        return arn

    step("downloading ffmpeg static build")
    tmp = Path(tempfile.mkdtemp(prefix="fflayer_"))
    tar_path = tmp / "ffmpeg.tar.xz"
    try:
        with urllib.request.urlopen(FFMPEG_URL, timeout=180) as resp, open(tar_path, "wb") as fh:
            shutil.copyfileobj(resp, fh)
    except Exception as exc:  # noqa: BLE001
        die(f"ffmpeg download failed: {exc}")

    entries: list[tuple[str, bytes, int]] = []
    with tf.open(tar_path, mode="r:xz") as tar:
        for member in tar.getmembers():
            base = Path(member.name).name
            if member.isfile() and base in ("ffmpeg", "ffprobe"):
                fh = tar.extractfile(member)
                assert fh is not None
                entries.append((base, fh.read(), 0o755))
                if len(entries) == 2:
                    break
    if len(entries) != 2:
        die(f"expected ffmpeg+ffprobe in tarball, found {[e[0] for e in entries]}")
    zip_bytes = _zip_bytes(entries)
    step(f"layer zip {len(zip_bytes)} bytes (ffmpeg+ffprobe, root, 0755)")
    key = f"layers/{LAYER_NAME}-{int(time.time())}.zip"
    s3.put_object(Bucket=bucket, Key=key, Body=zip_bytes)
    res = lam.publish_layer_version(
        LayerName=LAYER_NAME,
        Description="johnvansickle amd64 static ffmpeg/ffprobe at /opt root",
        Content={"S3Bucket": bucket, "S3Key": key},
        CompatibleArchitectures=["x86_64"],
        CompatibleRuntimes=["python3.11"],
    )
    step(f"published layer {LAYER_NAME} v{res['Version']}")
    return res["LayerVersionArn"]


# ---------------------------------------------------------------- Remotion CLI
def run_remotion(args: list[str], cwd: Path) -> str:
    node = shutil.which("node")
    if not node:
        die("node not found on PATH")
    cli = cwd / "node_modules" / "@remotion" / "cli" / "remotion-cli.js"
    if not cli.exists():
        die(f"missing {cli} - run npm ci in {cwd.name} first")
    env = os.environ.copy()
    env["REMOTION_AWS_REGION"] = env["AWS_REGION"] = env["AWS_DEFAULT_REGION"] = REGION
    cmd = [node, str(cli), "lambda", *args]
    proc = subprocess.run(cmd, cwd=str(cwd), env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace")
    out = (proc.stdout or "") + ("\n" + proc.stderr if proc.stderr else "")
    if proc.returncode != 0:
        die(f"`remotion lambda {' '.join(args)}` failed ({proc.returncode}):\n{out}")
    return out


def ensure_site() -> str:
    saved = read_env_file().get("SERVE_URL", "")
    if saved:
        step(f"reusing SERVE_URL from lambda.env: {saved}")
        return saved
    step(f"creating Remotion site {SITE_NAME} (bundle+upload, may take minutes)")
    out = run_remotion(
        ["sites", "create", ENTRY, f"--site-name={SITE_NAME}", f"--region={REGION}"], cwd=SITE_DIR)
    m = re.search(r"Serve\s*URL:\s*(\S+)", out, re.IGNORECASE)
    if not m:
        m = re.search(r"(https://[^\s\"']+)", out)
    if not m:
        die(f"could not parse Serve URL from sites create output:\n{out}")
    url = m.group(1).rstrip(".,")
    step(f"Serve URL: {url}")
    return url


def ensure_render_function() -> str:
    ls = run_remotion(["functions", "ls", f"--region={REGION}"], cwd=SITE_DIR)
    names = sorted(set(re.findall(r"remotion-render-[a-z0-9\-]+", ls)))
    if names:
        step(f"reusing render function {names[0]}")
        return names[0]
    step("deploying Remotion render function (2048MB, 900s, 1024MB disk, arm64 by CLI)")
    run_remotion(["functions", "deploy", "--memory=2048", "--timeout=900",
                  "--disk=1024", f"--region={REGION}"], cwd=SITE_DIR)
    ls = run_remotion(["functions", "ls", f"--region={REGION}"], cwd=SITE_DIR)
    names = sorted(set(re.findall(r"remotion-render-[a-z0-9\-]+", ls)))
    if not names:
        die(f"render function name not found after deploy:\n{ls}")
    step(f"render function {names[0]}")
    return names[0]


# ---------------------------------------------------------------- function zips
def upload_zip(s3, bucket: str, prefix: str, data: bytes) -> tuple[str, str]:
    key = f"{prefix}/{int(time.time())}-{secrets.token_hex(3)}.zip"
    s3.put_object(Bucket=bucket, Key=key, Body=data)
    return bucket, key


def build_prep_zip() -> bytes:
    tmp = Path(tempfile.mkdtemp(prefix="prepdeps_"))
    deps = tmp / "deps"
    step("pip installing prep deps for manylinux2014_x86_64 / py3.11")
    cmd = [sys.executable, "-m", "pip", "install", "--quiet", "--upgrade",
           "-r", str(PREP_DIR / "requirements.txt"), "--target", str(deps),
           "--platform", "manylinux2014_x86_64", "--python-version", "311",
           "--only-binary=:all:"]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.returncode != 0:
        die(f"pip platform install failed:\n{proc.stdout}\n{proc.stderr}")
    entries: list[tuple[str, bytes, int]] = [
        ("handler.py", (PREP_DIR / "handler.py").read_bytes(), 0o644)]
    for path in deps.rglob("*"):
        if path.is_file() and not path.is_symlink():
            arc = path.relative_to(deps).as_posix()
            entries.append((arc, path.read_bytes(), 0o755 if os.access(path, os.X_OK) else 0o644))
    data = _zip_bytes(entries)
    step(f"prep zip: {len(entries)} files, {len(data)} bytes")
    return data


def build_dispatch_zip() -> bytes:
    if not (DISPATCH_DIR / "node_modules").exists():
        step("npm ci in lambda/dispatch")
        proc = subprocess.run(["npm", "ci", "--omit=dev"], cwd=str(DISPATCH_DIR),
                              capture_output=True, text=True, encoding="utf-8", errors="replace")
        if proc.returncode != 0:
            die(f"npm ci failed:\n{proc.stdout}\n{proc.stderr}")
    entries: list[tuple[str, bytes, int]] = [
        ("index.mjs", (DISPATCH_DIR / "index.mjs").read_bytes(), 0o644),
        ("package.json", (DISPATCH_DIR / "package.json").read_bytes(), 0o644),
    ]
    nm = DISPATCH_DIR / "node_modules"
    for path in nm.rglob("*"):
        if path.is_file() and not path.is_symlink():
            arc = path.relative_to(DISPATCH_DIR).as_posix()
            entries.append((arc, path.read_bytes(), 0o755 if os.access(path, os.X_OK) else 0o644))
    data = _zip_bytes(entries)
    step(f"dispatch zip: {len(entries)} files, {len(data)} bytes")
    return data


# ---------------------------------------------------------------- Lambda functions
def wait_fn(lam, name: str) -> None:
    for waiter in ("function_active_v2", "function_updated_v2"):
        try:
            lam.get_waiter(waiter).wait(FunctionName=name, WaiterConfig={"Delay": 5, "MaxAttempts": 60})
        except Exception:  # noqa: BLE001 - waiter best-effort; state polled below
            pass
    for _ in range(60):
        cfg = lam.get_function_configuration(FunctionName=name)
        if cfg["State"] == "Active" and cfg["LastUpdateStatus"] in ("Successful", None):
            return
        if cfg["LastUpdateStatus"] == "Failed":
            die(f"function {name} update failed: {cfg.get('StateReason')}")
        time.sleep(5)


def _env_diff(current: dict | None, want: dict) -> bool:
    return (current or {}) != want


def upsert_function(lam, s3, bucket: str, *, name: str, runtime: str, handler: str,
                    timeout: int, memory: int, code_key: str, env: dict[str, str],
                    layers: list[str] | None = None, role_arn: str | None = None) -> None:
    kwargs: dict = {
        "Runtime": runtime, "Handler": handler, "Timeout": timeout, "MemorySize": memory,
        "Architectures": ["x86_64"], "Environment": {"Variables": env},
        "Code": {"S3Bucket": bucket, "S3Key": code_key},
    }
    if role_arn:
        kwargs["Role"] = role_arn
    if layers:
        kwargs["Layers"] = layers
    try:
        lam.get_function(FunctionName=name)
        step(f"updating function {name}")
        lam.update_function_code(FunctionName=name, S3Bucket=bucket, S3Key=code_key)
        wait_fn(lam, name)
        current = lam.get_function_configuration(FunctionName=name)
        cfg_kwargs = {k: v for k, v in kwargs.items() if k in (
            "Runtime", "Handler", "Timeout", "MemorySize", "Environment", "Layers", "Role")}
        if _env_diff((current.get("Environment") or {}).get("Variables"), env) or any(
                current.get(k) != v for k, v in cfg_kwargs.items() if k != "Environment"):
            lam.update_function_configuration(FunctionName=name, **cfg_kwargs)
            wait_fn(lam, name)
    except lam.exceptions.ResourceNotFoundException:
        step(f"creating function {name}")
        for attempt in range(6):
            try:
                lam.create_function(FunctionName=name, Publish=True, **kwargs)
                break
            except lam.exceptions.InvalidParameterValueException as exc:
                if "role" in str(exc).lower() and attempt < 5:
                    time.sleep(5)
                    continue
                raise
        wait_fn(lam, name)
    arn = lam.get_function_configuration(FunctionName=name)["FunctionArn"]
    step(f"{name} ready: {arn}")


# ---------------------------------------------------------------- HTTP API
def ensure_api(sts, lam, dispatch_arn: str) -> str:
    import boto3
    from botocore.exceptions import ClientError

    apig = boto3.client("apigatewayv2", region_name=REGION)
    acct = sts.get_caller_identity()["Account"]
    api = next((a for a in apig.get_apis()["Items"] if a.get("Name") == API_NAME), None)
    if api is None:
        step(f"creating HTTP API {API_NAME}")
        api = apig.create_api(Name=API_NAME, ProtocolType="HTTP",
                              Description="Remotion render dispatch (POST /render)")
    api_id = api["ApiId"]
    endpoint = api["ApiEndpoint"]

    uri = f"arn:aws:apigateway:{REGION}:lambda:path/2015-03-31/functions/{dispatch_arn}/invocations"
    integ = next((i for i in apig.get_integrations(ApiId=api_id)["Items"]
                  if i["IntegrationType"] == "AWS_PROXY"), None)
    if integ is None:
        step("creating AWS_PROXY integration (TimeoutInMilliseconds=1800000)")
        base = dict(ApiId=api_id, IntegrationType="AWS_PROXY", IntegrationUri=uri,
                    PayloadFormatVersion="2.0", IntegrationMethod="POST")
        try:
            integ = apig.create_integration(TimeoutInMilliseconds=1800000, **base)["Item"]
        except (ClientError, Exception) as exc:  # noqa: BLE001 - param validation fallback
            print(f"WARN: 1800000ms timeout rejected ({exc}); retrying without override")
            integ = apig.create_integration(**base)["Item"]
    elif integ.get("IntegrationUri") != uri:
        apig.update_integration(ApiId=api_id, IntegrationId=integ["IntegrationId"], IntegrationUri=uri)

    routes = apig.get_routes(ApiId=api_id)["Items"]
    if not any(r.get("RouteKey") == "POST /render" for r in routes):
        step("creating route POST /render")
        apig.create_route(ApiId=api_id, RouteKey="POST /render",
                          Target=f"integrations/{integ['IntegrationId']}",
                          AuthorizationType="NONE")

    stages = apig.get_stages(ApiId=api_id)["Items"]
    default = next((s for s in stages if s["StageName"] == "$default"), None)
    if default is None:
        step("creating stage $default (autoDeploy)")
        apig.create_stage(ApiId=api_id, StageName="$default", AutoDeploy=True)
    elif not default.get("AutoDeploy"):
        apig.update_stage(ApiId=api_id, StageName="$default", AutoDeploy=True)

    try:
        lam.add_permission(
            FunctionName=DISPATCH_FN, Action="lambda:InvokeFunction",
            Principal="apigateway.amazonaws.com", StatementId="apigw-render",
            SourceArn=f"arn:aws:execute-api:{REGION}:{acct}:{api_id}/*/POST/render")
        step("granted API Gateway invoke permission on dispatch")
    except lam.exceptions.ResourceConflictException:
        pass

    return f"{endpoint}/render"


# ---------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-remotion", action="store_true",
                    help="skip sites create / functions deploy; reuse lambda.env values")
    args = ap.parse_args()

    ensure_creds()
    import boto3

    sts = boto3.client("sts", region_name=REGION)
    lam = boto3.client("lambda", region_name=REGION)
    s3 = boto3.client("s3", region_name=REGION)
    step(f"caller {sts.get_caller_identity()['Arn']} (region {REGION})")

    role_arn = ensure_role(sts)
    bucket = ensure_bucket(sts)
    layer_arn = ensure_layer(s3, bucket)

    saved = read_env_file()
    if args.skip_remotion:
        serve_url = saved.get("SERVE_URL")
        render_fn = saved.get("REMOTION_FUNCTION")
        if not serve_url or not render_fn:
            die("--skip-remotion needs SERVE_URL + REMOTION_FUNCTION in lambda.env")
    else:
        serve_url = ensure_site()
        render_fn = ensure_render_function()

    api_key = saved.get("RENDER_API_KEY") or secrets.token_hex(32)

    # prep: python3.11, 300s, 1024MB, ffmpeg layer
    prep_env = {
        "ASSETS_BUCKET": bucket,
        "PUBLIC_ORIGIN": PUBLIC_ORIGIN,
        "SIGNED_TTL": "86400",
        "PREP_VOICE": "hi-IN-SwaraNeural",
    }
    _, prep_key = upload_zip(s3, bucket, "pkg/prep", build_prep_zip())
    upsert_function(lam, s3, bucket, name=PREP_FN, runtime="python3.11",
                    handler="handler.handler", timeout=300, memory=1024,
                    code_key=prep_key, env=prep_env, layers=[layer_arn], role_arn=role_arn)

    # dispatch: nodejs22.x, 900s, 1024MB
    dispatch_env = {
        "REMOTION_FUNCTION": render_fn,
        "SERVE_URL": serve_url,
        "PREP_FUNCTION": PREP_FN,
        "API_KEY": api_key,
        "COMPOSITION": COMPOSITION,
        "POLL_MS": "1500",
        "BUDGET_MS": "840000",
        "SIGN_TTL": "3600",
    }
    _, disp_key = upload_zip(s3, bucket, "pkg/dispatch", build_dispatch_zip())
    upsert_function(lam, s3, bucket, name=DISPATCH_FN, runtime="nodejs22.x",
                    handler="index.handler", timeout=900, memory=1024,
                    code_key=disp_key, env=dispatch_env, role_arn=role_arn)
    dispatch_arn = lam.get_function(FunctionName=DISPATCH_FN)["Configuration"]["FunctionArn"]

    invoke_url = ensure_api(sts, lam, dispatch_arn)

    write_env_file({
        "RENDER_API_KEY": api_key,
        "REMOTION_FUNCTION": render_fn,
        "SERVE_URL": serve_url,
        "PREP_FUNCTION": PREP_FN,
        "INVOKE_URL": invoke_url,
        "ASSETS_BUCKET": bucket,
        "AWS_REGION": REGION,
        "AWS_ACCOUNT_ID": sts.get_caller_identity()["Account"],
    })

    print("\n== provision summary ==")
    print(f"  POST endpoint : {invoke_url}")
    print(f"  X-Api-Key     : (RENDER_API_KEY in lambda.env)")
    print(f"  serveUrl      : {serve_url}")
    print(f"  render fn     : {render_fn}  (arm64, 2048MB, 900s)")
    print(f"  prep fn       : {PREP_FN}  (py3.11 x86_64, 300s, layer {LAYER_NAME})")
    print(f"  dispatch fn   : {DISPATCH_FN}  (nodejs22.x x86_64, 900s)")
    print(f"  assets bucket : {bucket}")
    print("  next: n8n Stage-4 edit -> E2E POST /render")


if __name__ == "__main__":
    main()
