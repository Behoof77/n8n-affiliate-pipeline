#!/usr/bin/env python3
"""Provision the Remotion Lambda render pipeline (migration task 5).

Idempotent. Region ap-south-1. Creates:
  * IAM exec role om-lambda-exec (+ inline S3/Invoke policy)
  * prep assets bucket om-prep-assets-<account>-aps1
  * ffmpeg static Lambda layer (johnvansickle amd64 -> /opt root, 0755)
  * Remotion site om-explainer via @remotion/lambda CLI        -> SERVE_URL
  * Remotion render fn (arm64 forced by CLI, 2048MB, 900s)     -> REMOTION_FUNCTION
  * prep Lambda    (python3.11, x86_64, 300s, + ffmpeg layer)
  * dispatch Lambda (nodejs22.x, x86_64, 900s, wired env)
  * API Gateway HTTP API  POST /render (AWS_PROXY, 1800s timeout)
  * lambda.env (gitignored, covered by *.env): RENDER_API_KEY, SERVE_URL, ...

Requires env AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY
(REMOTION_AWS_* accepted as alias).  Usage:
    python scripts/lambda_deploy.py [--skip-remotion]
"""
